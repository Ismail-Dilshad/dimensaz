process.env.VIDEO_TEST_RUN='1';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {run,ffmpeg} from '../renderer/ffmpeg-encoder.js';
import {ROOT} from '../engine/config.js';
import {writeJSON,load,revise,save,importMedia} from '../engine/project.js';
import {produce} from '../engine/production.js';
import {retimeSpeechEvents} from '../engine/speech-events.js';
const folder=await fs.mkdtemp(path.join(ROOT,'workspace','alignment-integration-'));
const audio=path.join(folder,'synthetic-cues.wav');
await run(ffmpeg,['-v','error','-n','-f','lavfi','-i',"aevalsrc='0.15*sin(2*PI*440*t)*(between(t,0.25,0.65)+between(t,1.25,1.75))':s=16000:d=2.2",'-c:a','pcm_s16le',audio]);
const effect=path.join(folder,'synthetic-click.wav');
await run(ffmpeg,['-v','error','-n','-f','lavfi','-i','sine=frequency=800:duration=0.08','-ar','16000',effect]);
const request=path.join(folder,'request.json');
await writeJSON(request,{schemaVersion:1,title:'Alignment integration synthetic fixture NOT speech',script:'سڵاو متمانە',voiceover:audio,resolution:{width:360,height:640},fps:12,preset:'active-word',wordAlignment:{audioSha256:createHash('sha256').update(await fs.readFile(audio)).digest('hex'),method:'manual-review',source:'Synthetic integration fixture: two generated tones at known intervals, NOT real speech alignment or linguistic review',reviewed:true,words:[{text:'سڵاو',start:.25,end:.65},{text:'متمانە',start:1.25,end:1.75}]}});
const first=await produce({manifest:request});
const p=await revise(first.job);
p.config.visuals=true;p.scenes[0].asset='communication';
await importMedia(p,effect,'sfx',0);
p.speechAnchors=[{kind:'object',wordIndex:1,edge:'start',offset:0},{kind:'camera',wordIndex:1,edge:'start',offset:0},{kind:'sfx',wordIndex:1,edge:'start',offset:0,mediaId:p.media.find(m=>m.kind==='sfx')!.id}];
retimeSpeechEvents(p);await save(p);
console.log(JSON.stringify(await produce({resume:first.job,revision:p.id}),null,2));
