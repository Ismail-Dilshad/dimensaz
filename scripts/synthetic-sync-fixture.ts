import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {ffmpeg,run} from '../renderer/ffmpeg-encoder.js';
import {ROOT} from '../engine/config.js';
import {writeJSON} from '../engine/project.js';
const folder=await fs.mkdtemp(path.join(ROOT,'workspace','synthetic-sync-'));
const audio=path.join(folder,'synthetic-tone.wav');
await run(ffmpeg,['-v','error','-n','-f','lavfi','-i','sine=frequency=440:duration=3','-ar','16000',audio]);
const request={schemaVersion:1,title:'Synthetic timing pipeline fixture NOT speech',script:'سڵاو کوردی',voiceover:audio,resolution:{width:360,height:640},fps:12,preset:'active-word',wordAlignment:{audioSha256:createHash('sha256').update(await fs.readFile(audio)).digest('hex'),method:'manual-review',source:'Synthetic test fixture: predetermined cue times on a sine wave; NOT real speech alignment',reviewed:true,words:[{text:'سڵاو',start:.3,end:1},{text:'کوردی',start:1.5,end:2.5}]}};
const file=path.join(folder,'request.json');await writeJSON(file,request);console.log(file);
