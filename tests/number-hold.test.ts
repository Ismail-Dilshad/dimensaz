import {it,expect} from 'vitest';
import fs from 'node:fs/promises';
import {chromium} from 'playwright';
import {chromiumExecutable} from '../src/renderer/browser-path.js';

it.skipIf(process.env.RUN_BROWSER_TESTS!=='1')('number buttons repeat while held and stop on release, limits, cancellation and removal',async()=>{
 const browser=await chromium.launch({executablePath:chromiumExecutable(),headless:true});
 const page=await browser.newPage({viewport:{width:800,height:600}});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.setContent('<div id="modal"></div><label for="value">Value</label><input type="number" id="value" min="0" max="100" step="0.01" value="0"><label for="bound">Bounded</label><input type="number" id="bound" min="0" max="3" value="0">');
  await page.addStyleTag({content:await fs.readFile('src/teach/ui/app.css','utf8')});
  await page.addScriptTag({content:await fs.readFile('src/teach/ui/core.js','utf8')});
  await page.clock.install();
  await page.evaluate('Controls.start()');
  await page.locator('#value').evaluate(el=>{el.setAttribute('data-changes','0');el.addEventListener('change',()=>{el.setAttribute('data-changes',String(Number(el.getAttribute('data-changes'))+1));});});
  const value=page.locator('#value'),plus=page.getByRole('button',{name:'Increase Value',exact:true}),minus=page.getByRole('button',{name:'Decrease Value',exact:true});
  await plus.hover();await page.mouse.down();
  expect(await value.inputValue()).toBe('0.01');
  await page.clock.runFor(600);
  expect(await value.inputValue()).toBe('0.05');
  expect(await value.getAttribute('data-changes')).toBe('0');
  await page.mouse.up();
  expect(await value.getAttribute('data-changes')).toBe('1');
  expect(await value.inputValue()).toBe('0.05');
  await page.clock.runFor(1000);
  expect(await value.inputValue()).toBe('0.05');
  await minus.hover();await page.mouse.down();await page.clock.runFor(1000);
  expect(await value.inputValue()).toBe('0');
  expect(await minus.isDisabled()).toBe(true);
  await page.mouse.up();
  const bounded=page.locator('#bound'),boundPlus=page.getByRole('button',{name:'Increase Bounded',exact:true});
  await boundPlus.hover();await page.mouse.down();await page.clock.runFor(1000);
  expect(await bounded.inputValue()).toBe('3');
  expect(await boundPlus.isDisabled()).toBe(true);
  await page.mouse.up();
  await plus.hover();await page.mouse.down();await page.clock.runFor(330);
  await page.mouse.move(790,590);const left=await value.inputValue();
  await page.clock.runFor(1000);expect(await value.inputValue()).toBe(left);await page.mouse.up();
  await plus.hover();await page.mouse.down();await page.clock.runFor(400);
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  const blurred=await value.inputValue();await page.clock.runFor(1000);
  expect(await value.inputValue()).toBe(blurred);await page.mouse.up();
  await plus.focus();await page.keyboard.down('Enter');await page.clock.runFor(600);
  const keyed=await value.inputValue();await page.keyboard.up('Enter');await page.clock.runFor(1000);
  expect(await value.inputValue()).toBe(keyed);
  expect(Number(keyed)).toBeGreaterThan(Number(blurred));
  await plus.focus();await page.keyboard.down('Space');await page.clock.runFor(400);
  const spaced=await value.inputValue();await page.keyboard.up('Space');await page.clock.runFor(1000);
  expect(await value.inputValue()).toBe(spaced);
  expect(Number(spaced)).toBeGreaterThan(Number(keyed));
  await plus.dispatchEvent('pointerdown',{pointerType:'touch',pointerId:9,button:0});
  await page.clock.runFor(400);
  await plus.dispatchEvent('pointercancel',{pointerType:'touch',pointerId:9});
  const cancelled=await value.inputValue();await page.clock.runFor(1000);
  expect(await value.inputValue()).toBe(cancelled);
  await plus.hover();await page.mouse.down();
  await value.evaluate(el=>{(el as HTMLInputElement).readOnly=true;});
  const readonly=await value.inputValue();await page.clock.runFor(1000);
  expect(await value.inputValue()).toBe(readonly);await page.mouse.up();
  await value.evaluate(el=>{(el as HTMLInputElement).readOnly=false;});
  await plus.hover();await page.mouse.down();
  const retained=await value.elementHandle(),removed=await value.inputValue();
  await value.evaluate(el=>el.closest('.number-control')!.remove());await page.clock.runFor(1000);
  expect(await retained!.evaluate(el=>(el as HTMLInputElement).value)).toBe(removed);await page.mouse.up();
  expect(errors).toEqual([]);
 }finally{await browser.close();}
},30000);
